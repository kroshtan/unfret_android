// Bundle the browser extension's page extractor (src/extract) into the app's assets.
//
//   node build.mjs --extension <dir>            write ../app/src/main/assets/unfret-extract.js
//   node build.mjs --extension <dir> --check    fail if the committed bundle differs from a fresh build
//
// <dir> is a copy of kroshtan/unfret_extension at the commit in EXTENSION_COMMIT (fetch-extension.sh makes one).
// The bundle is not minified, so it can be read and reviewed in this repository, and it is reproducible: the
// same extension commit and the same esbuild (package-lock.json) give the same bytes, which CI checks.
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join, relative, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { parseArgs } from "node:util";

import { build } from "esbuild";

const here = dirname(fileURLToPath(import.meta.url));
const { values } = parseArgs({
  options: { extension: { type: "string" }, check: { type: "boolean", default: false } },
});
if (!values.extension) {
  console.error("usage: node build.mjs --extension <unfret_extension checkout> [--check]");
  process.exit(2);
}
const extension = resolve(values.extension);
const commit = readFileSync(join(here, "EXTENSION_COMMIT"), "utf8").trim();
const out = join(here, "..", "app", "src", "main", "assets", "unfret-extract.js");

const result = await build({
  absWorkingDir: here,
  entryPoints: [join(here, "entry.ts")],
  alias: { "@unfret/extract": join(extension, "src", "extract", "index.ts") },
  bundle: true,
  format: "iife",
  // Android System WebView updates itself; Chrome 100 (2022) leaves room for phones that haven't in a while.
  target: "chrome100",
  minify: false,
  legalComments: "none",
  charset: "utf8",
  banner: {
    js:
      "// Generated by extractor/build.mjs from kroshtan/unfret_extension@" +
      commit +
      " (src/extract, MIT). Do not edit: see extractor/README.md.",
  },
  write: false,
  logLevel: "warning",
});
// esbuild names each source file in a comment, relative to this folder; name them the same wherever the
// extension's copy is, so the bundle depends only on the commit.
const bundle = result.outputFiles[0].text.replaceAll(`// ${relative(here, extension)}/`, "// unfret_extension/");

if (values.check) {
  let committed = "";
  try {
    committed = readFileSync(out, "utf8");
  } catch {
    // missing: reported below
  }
  if (committed !== bundle) {
    console.error(
      "app/src/main/assets/unfret-extract.js is not the bundle of unfret_extension@" +
        commit +
        ": run `make extractor` and commit the result.",
    );
    process.exit(1);
  }
  console.log(`unfret-extract.js matches unfret_extension@${commit}`);
} else {
  writeFileSync(out, bundle);
  console.log(`wrote ${out} (${bundle.length} bytes) from unfret_extension@${commit}`);
}
